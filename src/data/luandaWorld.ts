export function getDistrictAtPosition(x: number, z: number): DistrictName {
  if (x < -76) return 'Ilha de Luanda';
  if (x < -34) return 'Marginal de Luanda';
  if (x > 80 && z >= -66 && z <= 78) return 'Viana';
  if (z < -66 && x > 44) return 'Cazenga';
  if (z > 62) {
    if (x > 64) return 'Camama';
    if (x >= 2) return 'Talatona';
    return 'Benfica';
  }
  if (x > 40) return 'Kilamba';
  if (z < -6) return 'Ingombota';
  if (x > 6) return 'Talatona';
  return 'Maianga';
}

export function formatKwanzas(amount: number): string {
  return `${Math.round(amount).toLocaleString('pt-AO')} Kz`;
}
